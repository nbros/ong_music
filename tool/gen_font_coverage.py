"""Generates lib/src/data/font_coverage.g.dart: the characters that the fonts the web app bundles draw, as ranges of
code points, so that the app knows which characters of the catalogue need a font from elsewhere (see
lib/src/data/rare_characters.dart).

    python3 -I tool/gen_font_coverage.py \
        "$FLUTTER_ROOT/engine/src/flutter/txt/third_party/fonts/Roboto-Regular.ttf" \
        assets/fonts/Roboto-Medium.ttf > lib/src/data/font_coverage.g.dart

The first font is the Roboto Regular that `flutter build web --no-web-resources-cdn` bundles: flutter_tools copies
that file of the Flutter SDK (`packages/flutter_tools/lib/src/build_system/targets/web.dart`) to
assets/fonts/fallback/Roboto-Regular.ttf. The second is the app's own Roboto Medium. A character is covered when every
font given draws it: text of either weight finds it without a fallback font. Run it again when Flutter or one of the
fonts changes; test/font_coverage_test.dart fails until then.

Reads the `cmap` table of each font (formats 4 and 12, every subtable).
"""
import struct
import sys
import os


def code_points(file_path):
    data = open(file_path, 'rb').read()
    count = struct.unpack('>H', data[4:6])[0]
    tables = {}
    for i in range(count):
        tag, _, offset, _ = struct.unpack('>4sIII', data[12 + 16 * i:28 + 16 * i])
        tables[tag] = offset
    cmap = tables[b'cmap']
    subtables = struct.unpack('>H', data[cmap + 2:cmap + 4])[0]
    found = set()
    for i in range(subtables):
        _, _, offset = struct.unpack('>HHI', data[cmap + 4 + 8 * i:cmap + 12 + 8 * i])
        o = cmap + offset
        fmt = struct.unpack('>H', data[o:o + 2])[0]
        if fmt == 4:
            seg2 = struct.unpack('>H', data[o + 6:o + 8])[0]
            seg = seg2 // 2
            ends = struct.unpack('>%dH' % seg, data[o + 14:o + 14 + seg2])
            starts_at = o + 16 + seg2
            starts = struct.unpack('>%dH' % seg, data[starts_at:starts_at + seg2])
            deltas_at = starts_at + seg2
            deltas = struct.unpack('>%dh' % seg, data[deltas_at:deltas_at + seg2])
            offsets_at = deltas_at + seg2
            offsets = struct.unpack('>%dH' % seg, data[offsets_at:offsets_at + seg2])
            for s in range(seg):
                for cp in range(starts[s], ends[s] + 1):
                    if cp == 0xFFFF:
                        continue
                    if offsets[s] == 0:
                        glyph = (cp + deltas[s]) & 0xFFFF
                    else:
                        at = offsets_at + 2 * s + offsets[s] + 2 * (cp - starts[s])
                        glyph = struct.unpack('>H', data[at:at + 2])[0]
                        if glyph:
                            glyph = (glyph + deltas[s]) & 0xFFFF
                    if glyph:
                        found.add(cp)
        elif fmt == 12:
            groups = struct.unpack('>I', data[o + 12:o + 16])[0]
            for k in range(groups):
                start, end, _ = struct.unpack('>III', data[o + 16 + 12 * k:o + 28 + 12 * k])
                found.update(range(start, end + 1))
    return found


fonts = sys.argv[1:]
if not fonts:
    sys.exit(__doc__)
covered = set.intersection(*(code_points(f) for f in fonts))
ranges = []
for cp in sorted(covered):
    if ranges and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])

w = sys.stdout.write
w('// GENERATED by tool/gen_font_coverage.py from %s. Do not edit.\n'
  % ', '.join('%s (%d bytes)' % (os.path.basename(f), os.path.getsize(f)) for f in fonts))
w('// dart format off\n\n')
w('/// The characters the fonts of the web app draw (%d): first and last code point of each range, ascending.\n'
  % len(covered))
w('const List<int> bundledFontRanges = [\n')
for i in range(0, len(ranges), 8):
    w('  ' + ', '.join('0x%04X, 0x%04X' % (a, b) for a, b in ranges[i:i + 8]) + ',\n')
w('];\n')
