"""Generates lib/src/data/fold_table.g.dart: a one-to-one (UTF-16 code unit to
UTF-16 code unit) case and diacritic fold, so that a folded string keeps the
length of the original and match offsets can be mapped back to it.

    python3 -I tool/gen_fold_table.py > lib/src/data/fold_table.g.dart

For each BMP character: decompose (NFD), drop the Combining Diacritical Marks
(U+0300-U+036F: accents of Latin, Greek, Cyrillic... but not, say, the Japanese
voicing marks, which make other syllables), lowercase; the
mapping is kept only when the result is a single BMP character. Characters that
would expand (ß, æ, Hangul syllables...) are only lowercased, or left as is.
A few letters with a stroke, which Unicode does not decompose, are added by hand.

Also emits the canonical compositions "letter + combining diacritical mark" to
one BMP character (`e` + U+0301 gives `é`), used to compose text that arrives
decomposed, so that it folds, matches and displays like precomposed text.
"""
import unicodedata, sys

EXTRA = {'ø': 'o', 'Ø': 'o', 'ł': 'l', 'Ł': 'l', 'đ': 'd', 'Đ': 'd', 'ħ': 'h', 'Ħ': 'h',
         'ŧ': 't', 'Ŧ': 't', 'ı': 'i', 'ƀ': 'b', 'ɨ': 'i', 'ʉ': 'u', 'ǥ': 'g', 'Ǥ': 'g'}

def fold1(c):
    if c in EXTRA:
        return EXTRA[c]
    d = ''.join(x for x in unicodedata.normalize('NFD', c) if not 0x300 <= ord(x) <= 0x36F).lower()
    if len(d) == 1 and ord(d) < 0x10000:
        return EXTRA.get(d, d)
    lo = c.lower()
    if len(lo) == 1 and ord(lo) < 0x10000:
        return EXTRA.get(lo, lo)
    return c

src, dst = [], []
for cp in range(0x10000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    f = fold1(c)
    if f != c:
        src.append(cp); dst.append(ord(f))

def runs(values):
    # delta-free plain list, 16 per line
    out = []
    for i in range(0, len(values), 16):
        out.append('  ' + ', '.join('0x%04X' % v for v in values[i:i + 16]) + ',')
    return '\n'.join(out)

w = sys.stdout.write
w('// GENERATED by tool/gen_fold_table.py (Unicode %s). Do not edit.\n' % unicodedata.unidata_version)
w('// ignore_for_file: lines_longer_than_80_chars\n')
w('// dart format off\n\n')
w('/// Code units that fold to something else (sorted), see [foldTo].\n')
w('const List<int> foldFrom = [\n%s\n];\n\n' % runs(src))
w('/// What each [foldFrom] code unit folds to.\n')
w('const List<int> foldTo = [\n%s\n];\n' % runs(dst))

# canonical pairs (base, mark in U+0300-U+036F) -> precomposed character
pairs = []
for cp in range(0x10000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    d = unicodedata.decomposition(chr(cp)).split()
    if len(d) != 2 or d[0].startswith('<'):
        continue
    base, mark = int(d[0], 16), int(d[1], 16)
    if base >= 0x10000 or not 0x300 <= mark <= 0x36F:
        continue
    if unicodedata.normalize('NFC', chr(base) + chr(mark)) != chr(cp):
        continue  # composition exclusion
    pairs.append((base * 0x10000 + mark, cp))
pairs.sort()

def runs32(values):
    out = []
    for i in range(0, len(values), 12):
        out.append('  ' + ', '.join('0x%08X' % v for v in values[i:i + 12]) + ',')
    return '\n'.join(out)

w('\n/// `base * 0x10000 + mark` for every canonical pair of a character and a\n')
w('/// combining diacritical mark (U+0300-U+036F) that composes to [composeTo].\n')
w('const List<int> composeFrom = [\n%s\n];\n\n' % runs32([k for k, _ in pairs]))
w('/// The precomposed character of each [composeFrom] pair.\n')
w('const List<int> composeTo = [\n%s\n];\n' % runs([v for _, v in pairs]))
sys.stderr.write('%d fold entries, %d compositions\n' % (len(src), len(pairs)))
