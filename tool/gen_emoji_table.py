"""Generates lib/src/data/emoji.g.dart: the characters with the Unicode property Emoji, those the colour emoji font
draws, as ranges of code points (see lib/src/data/font_kits.dart).

    curl -O https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt
    python3 -I tool/gen_emoji_table.py emoji-data.txt > lib/src/data/emoji.g.dart

The property Emoji, not Emoji_Presentation: the web engine tries the colour emoji font right after Roboto, so a
symbol whose default presentation is text (▶ ♥ ✔ ❤ without U+FE0F) is drawn in colour by the engine's own fallback
too; the kits keep it so. Run it again with the data of a later Unicode version when Noto Color Emoji follows one.
"""
import re
import sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
version = '?'
points = set()
for line in open(sys.argv[1], encoding='utf-8'):
    found = re.match(r'#\s*Version:\s*(\S+)', line)
    if found:
        version = found.group(1)
    data = line.split('#')[0].strip()
    if not data:
        continue
    cps, prop = (part.strip() for part in data.split(';'))
    if prop != 'Emoji':
        continue
    first, _, last = cps.partition('..')
    points.update(c for c in range(int(first, 16), int(last or first, 16) + 1) if c >= 0x80)

ranges = []
for cp in sorted(points):
    if ranges and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])

w = sys.stdout.write
w('// GENERATED by tool/gen_emoji_table.py from emoji-data.txt (Unicode %s). Do not edit.\n' % version)
w('// dart format off\n\n')
w('/// The characters beyond ASCII with the Unicode property Emoji (%d): first and last code point of each range,\n'
  % len(points))
w('/// ascending.\n')
w('const List<int> emojiRanges = [\n')
for i in range(0, len(ranges), 8):
    w('  ' + ', '.join('0x%04X, 0x%04X' % (a, b) for a, b in ranges[i:i + 8]) + ',\n')
w('];\n')
